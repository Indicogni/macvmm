/// `const NAME=0x...`: the value as `u64`. `i32` constants sign-extend, exactly like the C
/// side's `(unsigned long long)` conversion of a negative `int`.
macro_rules! consts {
    ($out:ident, $($name:ident),* $(,)?) => {
        $( writeln!($out, "const {}={:#x}", stringify!($name), $name as u64)?; )*
    };
}

macro_rules! types {
    ($out:ident, $($t:ident),* $(,)?) => {
        $( writeln!($out, "size {}={} align={}", stringify!($t), size_of::<$t>(), align_of::<$t>())?; )*
    };
}

macro_rules! fields {
    ($out:ident, $($t:ident . $($f:ident).+);* $(;)?) => {
        $( writeln!(
            $out,
            "offset {}.{}={}",
            stringify!($t),
            [$(stringify!($f)),+].join("."),
            offset_of!($t, $($f).+)
        )?; )*
    };
}

macro_rules! fns {
    ($out:ident, $($name:ident),* $(,)?) => {
        $( writeln!($out, "fn {}", stringify!($name))?; )*
    };
}

