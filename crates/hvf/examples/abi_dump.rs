//! `cargo run -p hvf --example abi_dump`: the Rust side of the ABI oracle (ADR-0002 item 3).
//!
//! **Why:** `src/ffi.rs` is transcribed from the SDK headers by hand, so it can be wrong in ways
//! the compiler cannot see: a wrong enumerator value, a `u32` where the header says `u16`, a
//! missing padding byte. This program prints every constant, type layout and function name that
//! the Rust declarations claim, in the same format as `abi/abi_dump.c`, which clang compiles
//! against the real headers. `scripts/check-ffi.sh` diffs the two outputs and also checks that
//! every `pub const`, `pub type` and `pub fn` in `ffi.rs` appears here, so nothing escapes the
//! comparison.
//!
//! The `SysReg` constants come from `regs.rs`, where they are built from ARM ARM coordinates:
//! the oracle therefore also checks our `op0<<14 | op1<<11 | CRn<<7 | CRm<<3 | op2` encoding.

use core::mem::{align_of, offset_of, size_of};
